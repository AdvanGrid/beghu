//! The PR view's analysis, shared by every producer and consumer of one: the server, the beghu
//! CLI, CI, `./dev-ctl`, the test harness and the tiler. None of them carries its own copy of a
//! rule.
//!
//! - [`schema`]: the Rust types, which are the schema. `cargo test` generates them into
//!   `generated/schema.ts` (served to the agent as `schema.ts`, and copied to the web app's
//!   `web/src/bindings/analysis.ts`).
//! - [`validate()`]: migrates, then checks an analysis, with or without a [`Reader`] over the two
//!   checkouts, into one [`Report`].
//! - [`migrate`]: the chain of schema version steps.
//! - [`check_split`], [`merge()`] and [`finish`]: the split procedure's tools.
//!
//! No I/O and no SQL.

pub mod migrate;
pub mod reader;
pub mod report;
pub mod schema;
