//! `schema.ts` and the versioning guards (spec #175, "Migrations"), through the crate's entry
//! points.
//!
//! This test writes `generated/schema.ts` and its copy in the web app, as ts-rs writes the
//! server's bindings: run `cargo test -p analysis` after changing a type or a doc comment, and
//! commit both files. CI fails when either is stale.

mod common;

use std::path::{Path, PathBuf};

use analysis::migrate::STEPS;
use analysis::schema_ts::{body, shape, upload_shape, upload_types};
use analysis::{CHAIN, Context, Evidence, VERSION, validate_value};
use serde_json::Value;
use sha2::{Digest, Sha256};

fn root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).to_owned()
}

fn header_value<'a>(text: &'a str, key: &str) -> Option<&'a str> {
    text.lines()
        .take_while(|l| l.starts_with("//"))
        .find_map(|l| l.strip_prefix(&format!("// {key}: ")))
}

/// Guard 1: the generated schema records its version and the hash of the upload's shape (the
/// types `Analysis` reaches, comments stripped). A shape change without a version bump fails; a
/// doc-comment edit, or a change to the split procedure's types, doesn't. A file without the
/// header fails too: the guard never skips.
#[test]
fn schema_ts_is_current_and_its_shape_is_versioned() {
    let body = body();
    // A `*/` inside a doc comment would end the TypeScript comment early.
    for (i, line) in body.lines().enumerate() {
        let t = line.trim();
        assert!(
            !t.contains("*/") || t == "*/",
            "schema.ts line {}: a doc comment holds `*/`: {line}",
            i + 7
        );
    }
    let hash = format!(
        "sha256:{:x}",
        Sha256::digest(upload_shape(&body).as_bytes())
    );
    let path = root().join("generated/schema.ts");
    let committed = std::fs::read_to_string(&path).unwrap_or_default();
    let (Some(v), Some(h)) = (
        header_value(&committed, "schema-version"),
        header_value(&committed, "shape-hash"),
    ) else {
        panic!(
            "generated/schema.ts has no `schema-version` and `shape-hash` header, so the guard can't tell \
             whether the shape changed: restore it (`git checkout -- crates/analysis/generated/schema.ts`) \
             and run again"
        );
    };
    let v: u32 = v.parse().expect("schema-version is a number");
    assert!(
        v <= VERSION,
        "generated/schema.ts says version {v}, but VERSION is {VERSION}"
    );
    assert!(
        v < VERSION || h == hash,
        "the analysis's shape changed but migrate::VERSION is still {VERSION}: bump VERSION to {} and add the \
         migration step from version {VERSION} to migrate::STEPS (doc-comment edits don't need this). \
         The new shape's hash is {hash}",
        VERSION + 1
    );
    let text = format!(
        "// The PR view analysis's schema: every type the agent reads or writes. Generated by\n\
         // `cargo test -p analysis` from the Rust types in crates/analysis/src (schema.rs, tools.rs,\n\
         // report.rs), doc comments included. Don't edit it: change the types and their comments.\n\
         // schema-version: {VERSION}\n\
         // shape-hash: {hash}\n\n{body}"
    );
    for p in [path, root().join("../../web/src/bindings/analysis.ts")] {
        if std::fs::read_to_string(&p).ok().as_deref() != Some(text.as_str()) {
            std::fs::write(&p, &text).unwrap_or_else(|e| panic!("writing {}: {e}", p.display()));
        }
    }
    assert_eq!(
        analysis::SCHEMA_TS,
        text,
        "generated/schema.ts was stale: run cargo test again and commit it"
    );
}

/// The shape ignores comments, not code: a field's name or type changes the hash.
#[test]
fn the_shape_hash_reads_through_comments_only() {
    let a = "/** The one. */\nexport type A = { a: string, };\n";
    let commented = "/** Another doc. */\n// and a note\nexport type A = { a: string, };\n";
    let renamed = "/** The one. */\nexport type A = { b: string, };\n";
    assert_eq!(shape(a), shape(commented));
    assert_ne!(shape(a), shape(renamed));
    assert_ne!(shape("type A = \"x//y\";"), shape("type A = \"x\";"));
}

/// The hash covers the upload's types and nothing else: a change to a hint or to `split.json`
/// stores nothing differently, so it needs no migration; a change to a type `Analysis` reaches
/// does.
#[test]
fn the_shape_hash_covers_only_the_upload() {
    let body = body();
    let names = upload_types();
    assert!(names.contains("Analysis") && names.contains("Evidence"));
    for not in [
        "Split",
        "Hint",
        "Resolution",
        "PreviousIds",
        "Report",
        "Fragment",
    ] {
        assert!(!names.contains(not), "{not} isn't part of an upload");
    }
    let edit = |from: &str, to: &str| {
        assert!(body.contains(from), "{from}");
        upload_shape(&body.replacen(from, to, 1))
    };
    let now = upload_shape(&body);
    assert_eq!(
        now,
        edit(
            "export type Split = {",
            "export type Split = { extra: string,"
        )
    );
    assert_eq!(
        now,
        edit(
            "export type Fragment = ",
            "export type Fragment = { extra: string } & "
        )
    );
    assert_eq!(
        now,
        edit(
            "export type Hint =",
            "export type Hint = { kind: \"extra\" } |"
        )
    );
    assert_ne!(
        now,
        edit(
            "export type Drawn = {",
            "export type Drawn = { extra: string,"
        )
    );
    assert_ne!(
        now,
        edit(
            "export type Analysis = {",
            "export type Analysis = { extra: string,"
        )
    );
}

/// Guard 2: one step per version after the first, in order, from version 1.
#[test]
fn the_migration_chain_has_one_step_per_version() {
    let steps = STEPS;
    assert_eq!(
        steps.len() as u32,
        VERSION - 1,
        "the chain has {} steps for version {VERSION}",
        steps.len()
    );
    for (i, s) in steps.iter().enumerate() {
        assert_eq!(
            s.from,
            i as u32 + 1,
            "step {i} leaves version {}, not {}",
            s.from,
            i + 1
        );
    }
    assert_eq!(CHAIN.version, VERSION);
}

/// Every code evidence in a file, wherever its version keeps it: path, range and snippet.
fn evidence_in(v: &Value, out: &mut Vec<(String, u64, u64, String)>) {
    match v {
        Value::Object(o) => {
            if let (Some(p), Some(s), Some(e), Some(t)) = (
                o.get("path").and_then(Value::as_str),
                o.get("start").and_then(Value::as_u64),
                o.get("end").and_then(Value::as_u64),
                o.get("snippet").and_then(Value::as_str),
            ) {
                out.push((p.to_owned(), s, e, t.to_owned()));
            }
            o.values().for_each(|x| evidence_in(x, out));
        }
        Value::Array(a) => a.iter().for_each(|x| evidence_in(x, out)),
        _ => {}
    }
}

/// The committed recordings: the crate's sample, and the recorded analyses under
/// `fixtures/pr-view/recordings/` once slice 4 commits them.
fn recordings() -> Vec<PathBuf> {
    let mut out = vec![root().join("tests/sample/analysis.json")];
    let dir = root().join("../../fixtures/pr-view/recordings");
    if let Ok(entries) = std::fs::read_dir(dir) {
        let mut more: Vec<PathBuf> = entries
            .filter_map(Result::ok)
            .map(|e| e.path())
            .filter(|p| p.extension().is_some_and(|x| x == "json"))
            .collect();
        more.sort();
        out.extend(more);
    }
    out
}

/// Guard 3: every committed recording migrates and validates, and its evidence is the same
/// before and after.
#[test]
fn every_recording_migrates_and_validates_with_its_evidence_untouched() {
    for path in recordings() {
        let text = std::fs::read_to_string(&path).unwrap();
        let before: Value = serde_json::from_str(&text).unwrap();
        let out = validate_value(before.clone(), &Context::default(), None);
        assert!(
            out.report.errors.is_empty(),
            "{}: {:#?}",
            path.display(),
            out.report.errors
        );
        let a = out.analysis.expect("it validated");
        let mut was = Vec::new();
        evidence_in(&before, &mut was);
        let now: Vec<_> = a
            .claims
            .iter()
            .flat_map(|c| &c.evidence)
            .filter_map(|e| match e {
                Evidence::Code {
                    path,
                    start,
                    end,
                    snippet,
                    ..
                } => Some((
                    path.clone(),
                    u64::from(*start),
                    u64::from(*end),
                    snippet.clone(),
                )),
                _ => None,
            })
            .collect();
        was.sort();
        let mut now = now;
        now.sort();
        assert_eq!(
            was,
            now,
            "{}: a migration step changed quoted code or line ranges",
            path.display()
        );
    }
}
